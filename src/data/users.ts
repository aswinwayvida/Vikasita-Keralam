export const isBjpMemberUser = (user: AppUser | null | undefined): boolean => {
  if (!user) return false;
  const nameLower = user.name.toLowerCase();
  if (nameLower.includes("muraleedharan") || nameLower.includes("suresh gopi")) {
    return true;
  }
  return (
    user.category === "bjp_member" ||
    user.designationEn.toLowerCase().includes("bjp") ||
    user.designationMl.includes("ബി.ജെ.പി") ||
    user.email.toLowerCase().includes("bjp")
  );
};

